#!/usr/bin/env bash
#
# BH-150 — опис компонента для pkgbuild: забороняємо інсталятору і переставляти
# наш застосунок, і пропускати установку.
#
#   scripts/mac_component_plist.sh <тека-корінь> <шлях до component.plist>
#
# Окремим файлом, а не рядками в mac_build_pkg.sh, щоб це можна було прогнати
# тестом як є (tests/test_mac_installer_assets.py) — CI на Linux його пропустить,
# локально на маку він перевіряє саме той код, що потім збирає реліз.
#
# ЩО САМЕ ТУТ ЗНІМАЄТЬСЯ І ЧОМУ:
#
# `BundleIsRelocatable` — типово `true`. Тоді installd через Spotlight шукає
# наявну копію з тим самим CFBundleIdentifier і кладе вміст ПОВЕРХ НЕЇ, де б та
# не лежала. 13.09 пакет так поставився в теку `dist/` розробника: установка
# «успішна», агент указує на /Applications, а там порожньо. Наш шлях зашитий і
# в LaunchAgent, і в кнопку видалення, і в перевірку «вже встановлено», тож
# переміщення для нас — вада.
#
# `BundleIsVersionChecked` — типово `true`, тобто «не ставити, якщо на диску
# НОВІША версія». Знайдено ревʼю: копія, зібрана руками з більшим номером
# версії, тихо блокує розпакування — скрипти при цьому відпрацюють, файл на
# місці й запускається, і всі перевірки скажуть «усе гаразд», хоч підписаний
# вміст із пакета не поставився. Пакет мусить перемагати завжди.
#
# ЦІНА ЦЬОГО, і вона свідома (знайдено другим колом ревʼю): разом із тим
# зникає єдиний захист від відкату. Тепер старіший пакет, запущений руками —
# скажімо, той, що місяць лежить у Downloads, — тихо перезапише новішу
# установку. Ми на це згодні: пакет один на всі машини, оновлення веде кнопка
# в дашборді (вона завжди тягне releases/latest), а «переставити поверх» мусить
# лікувати зламану установку, а не впиратись у номер версії. Якщо колись
# зʼявиться канал, де користувач сам обирає версію, захист треба буде повернути
# явною перевіркою в дашборді, а не цим прапорцем.
set -euo pipefail

ROOT="${1:?перший аргумент — тека, яку пакуємо}"
OUT="${2:?другий аргумент — куди покласти component.plist}"

pkgbuild --analyze --root "$ROOT" "$OUT"

# Далі ми правимо ПЕРШИЙ запис масиву. Це правильно, поки в пакеті рівно один
# бандл — наш застосунок (PyInstaller onefile, без вкладених фреймворків).
# Щойно з'явиться вкладений бандл зі своїм ідентифікатором, installd зможе
# переставити окремо його, а ми цього не знімемо. Тому не «мовчки далі»:
if ! /usr/libexec/PlistBuddy -c "Print :0" "$OUT" >/dev/null 2>&1; then
  echo "::error::в описі компонента немає жодного бандла — у $ROOT не той вміст"
  exit 1
fi
if /usr/libexec/PlistBuddy -c "Print :1" "$OUT" >/dev/null 2>&1; then
  echo "::error::в описі компонента більше одного бандла — зніми прапорці з усіх"
  exit 1
fi
if /usr/libexec/PlistBuddy -c "Print :0:ChildBundles" "$OUT" >/dev/null 2>&1; then
  echo "::error::у застосунку з'явились вкладені бандли — зніми прапорці і з них"
  exit 1
fi

for key in BundleIsRelocatable BundleIsVersionChecked; do
  /usr/libexec/PlistBuddy -c "Set :0:$key false" "$OUT"
  # Перевіряємо ЗНАЧЕННЯМ, а не кодом виходу: PlistBuddy на помилку в команді
  # часто повертає 0 і пише текст помилки в stdout.
  /usr/libexec/PlistBuddy -c "Print :0:$key" "$OUT" | grep -qx false \
    || { echo "::error::не вдалося зняти $key"; exit 1; }
done

echo "==> опис компонента: переміщення й перевірку версії вимкнено ($OUT)"
