"""Одне місце, яке знає встановлену версію менеджера.

Файл `VERSION` лежить у корені — і поруч із кодом у замороженій збірці теж
(PyInstaller кладе його в `_MEIPASS`), тож шлях рахуємо ВІД КОДУ, а не від
робочої теки: у exe вона довільна.

Доти цей самий рядок стояв у чотирьох місцях — у двох із різною глибиною
шляху й із різним запасним значенням («unknown» у маршруті версії, «0.0.0» у
звітах нагору). Запасне значення лишається за викликом, бо воно й справді
різне: людині в дашборді «unknown» чесніше, а серверу логів потрібен номер.
"""

from pathlib import Path

VERSION_FILE = Path(__file__).resolve().parent.parent / "VERSION"


def installed_version(default: str = "0.0.0") -> str:
    """Версія з файла `VERSION`, або `default`, якщо файла немає."""
    try:
        return VERSION_FILE.read_text().strip() or default
    except OSError:
        # Файл могли зняти разом із теками збірки — версія не привід падати.
        return default
