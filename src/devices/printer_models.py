_TOKEN_RE = re.compile(r"[A-Z0-9]+")

# Ідентифікатори USB у будь-якому написанні, які треба викинути ДО розбору
# назви на токени.
#
# ЧОМУ. PID — це чотири шістнадцяткові цифри, і більшість ядер у таблиці теж
# виглядають як чотири символи з [0-9A-F] (`410B`, `330B`, `246B`…). Тобто
# звичайний ESC/POS-принтер на чипі STMicro міг «упізнатись» як TSPL через
# власний PID — і перестати різати чеки, друкуючи сміття.
#
# Перша редакція вирізала лише форму `0483:410B`, і друге коло ревʼю показало,
# що цього мало: Windows Device Manager дає ідентифікатор як
# `USB\VID_0483&PID_410B&REV_0100`, а такий рядок цілком може потрапити в
# поле назви при ручній реєстрації — саме в тому випадку «скан не бачить
# принтер», заради якого ручна реєстрація й існує. Тому ловимо всі три
# написання: з двокрапкою, з дефісом і з префіксами VID_/PID_.
_USB_ID_RE = re.compile(
    r"(?:\bVID[_-]?[0-9A-F]{4}\b)"      # VID_0483
    r"|(?:\bPID[_-]?[0-9A-F]{4}\b)"     # PID_410B
    r"|(?:\bREV[_-]?[0-9A-F]{4}\b)"     # REV_0100 — той самий ризик
    r"|(?:\b[0-9A-F]{4}[:\-][0-9A-F]{4}\b)",  # 0483:410B, 0483-410B
)


def protocol_for_model(label: Optional[str]) -> Optional[str]:
    """`"4BARCODE 3B-365B"` → `"tspl"`. None, якщо модель невідома.

    None означає саме «не знаю», а не «ESC/POS»: викликач мусить свідомо
    обрати дефолт, а не отримати його непомітно.
    """
    if not label:
        return None
    tokens = _TOKEN_RE.findall(_USB_ID_RE.sub(" ", label.upper()))
    for token in tokens:
        if token in TSPL_MODEL_CORES:
            return "tspl"
    # Свідомо БЕЗ зворотного списку «а це точно ESC/POS». Три родові чекові
    # моделі того набору (XP-58 / XP-76 / XP-80) нічого б не додали: ESC/POS
    # і так є дефолтом, а перелічувати те, що й так дефолт, означає плодити
    # другий список, який розійдеться з першим.
    return None
