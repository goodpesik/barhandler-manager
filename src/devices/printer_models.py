"""BH-160 — якою мовою говорить це залізо.

Протокол друку — властивість ПРИСТРОЮ, а не ролі, яку йому призначили.
Доти він дефолтився від ролі (`kind == label → tspl`, решта → `escpos`), і
через це оператор, обравши «чек» на етикетковому принтері, мовчки отримував
ESC/POS: прошивка приймає байти й викидає їх, а ми рапортуємо успіх.

ЗВІДКИ ТАБЛИЦЯ. З набору драйверів самого виробника — `net.xprinter.drv.receipt`
3.13.1, 313 PPD-файлів. Кожен PPD прямо каже, яким фільтром CUPS друкує:
`rastertosnailtspl` (TSPL) або `rastertosnailep` (ESC/POS). Розподіл: 310 → TSPL,
три → ESC/POS, і ці три — родові `XP-58` / `XP-76` / `XP-80`, тобто звичайні
чекові принтери, названі за шириною паперу.

ЧОМУ САМЕ НАЗВА, А НЕ ОПИТУВАННЯ ПРИСТРОЮ. І ESC/POS, і TSPL мають команди
статусу, але прочитати відповідь можна лише там, де є зворотний канал — USB
і мережа. На вінда-спулері його немає взагалі: `Win32Raw` пише й не читає.
А саме спулер — наш штатний шлях на вінді. Назва ж приходить зі СКАНУ, тож
працює на всіх транспортах.

ЧОМУ ЗБІГ ЗА ЯДРОМ НАЗВИ, А НЕ ЗА ПОВНОЮ. Те саме залізо продають під різними
марками: у клієнта принтер зветься `4BARCODE 3B-365B`, і це той самий
Xprinter XP-365B. Спільне в них — ядро моделі `365B`. Тому шукаємо ядро як
окреме слово в назві пристрою.

ЩО РОБИТИ З НЕВІДОМОЮ МОДЕЛЛЮ. Нічого не вигадувати: таблиця — це зріз однієї
версії драйверів, нові моделі зʼявлятимуться. Невідома назва повертає None,
і рішення приймає той, хто кличе: дефолт або оператор. Мовчазної підміни, з
якої почалась ця історія, бути не повинно.
"""

